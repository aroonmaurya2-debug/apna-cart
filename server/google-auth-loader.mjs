export async function load(url, context, defaultLoad) {
  const result = await defaultLoad(url, context, defaultLoad)
  if (!url.endsWith('/server/server.mjs')) return result

  const injected = [
    '',
    '// Firebase auth bridges injected at runtime.',
    "app.post('/api/auth/firebase-google', async (request, response) => {",
    "  const idToken = clean(request.body?.idToken)",
    "  if (!idToken) return response.status(400).json({ message: 'Firebase ID token is required.' })",
    '  try {',
    "    const { getAuth } = await import('firebase-admin/auth')",
    '    const decoded = await getAuth().verifyIdToken(idToken)',
    '    const contact = normaliseContact(decoded.email || decoded.phone_number || decoded.uid)',
    "    const displayName = clean(decoded.name || decoded.email || 'Apna Cart User')",
    "    const token = crypto.randomBytes(32).toString('hex')",
    "    sessions.set(token, { name: displayName, contact, createdAt: Date.now(), firebaseUid: decoded.uid, provider: 'google' })",
    '    return response.json({ token, user: { name: displayName, contact }, firebaseUid: decoded.uid })',
    '  } catch (error) {',
    "    console.error('Firebase Google authentication failed:', error.message)",
    "    return response.status(401).json({ message: 'Google login verify nahi ho saka. Firebase/Google settings check karein.' })",
    '  }',
    '})',
    "app.post('/api/auth/firebase-email', async (request, response) => {",
    "  const idToken = clean(request.body?.idToken)",
    "  if (!idToken) return response.status(400).json({ message: 'Firebase ID token is required.' })",
    '  try {',
    "    const { getAuth } = await import('firebase-admin/auth')",
    '    const decoded = await getAuth().verifyIdToken(idToken)',
    '    const contact = normaliseContact(decoded.email || decoded.uid)',
    "    const displayName = clean(decoded.name || decoded.email || 'Apna Cart User')",
    "    const token = crypto.randomBytes(32).toString('hex')",
    "    sessions.set(token, { name: displayName, contact, createdAt: Date.now(), firebaseUid: decoded.uid, provider: 'email-link' })",
    '    return response.json({ token, user: { name: displayName, contact }, firebaseUid: decoded.uid })',
    '  } catch (error) {',
    "    console.error('Firebase email authentication failed:', error.message)",
    "    return response.status(401).json({ message: 'Email login verify nahi ho saka. Firebase email settings check karein.' })",
    '  }',
    '})',
    '',
    '// Customer order cancellation, return and refund-request bridge.',
    "const findCustomerOrder = async (request, response) => {",
    '  const session = getSession(request)',
    "  if (!session) { response.status(401).json({ message: 'Please login again.' }); return null }",
    '  const id = String(request.params.id || "")',
    '  if (!id) { response.status(400).json({ message: "Order ID is required." }); return null }',
    '  if (ordersCollection) {',
    '    const reference = ordersCollection.doc(id); const snapshot = await reference.get()',
    "    if (!snapshot.exists) { response.status(404).json({ message: 'Order not found.' }); return null }",
    '    const order = snapshot.data()',
    '    const contacts = [order.customer?.contact, order.contact, order.email, order.customer?.email, order.phone].map(value => clean(value).toLowerCase()).filter(Boolean)',
    '    if (!contacts.includes(clean(session.contact).toLowerCase())) { response.status(403).json({ message: "You cannot modify this order." }); return null }',
    '    return { reference, order }',
    '  }',
    '  const orders = await readOrders(); const index = orders.findIndex(item => String(item.id) === id)',
    '  if (index < 0) { response.status(404).json({ message: "Order not found." }); return null }',
    '  const order = orders[index]',
    '  const contacts = [order.customer?.contact, order.contact, order.email, order.customer?.email, order.phone].map(value => clean(value).toLowerCase()).filter(Boolean)',
    '  if (!contacts.includes(clean(session.contact).toLowerCase())) { response.status(403).json({ message: "You cannot modify this order." }); return null }',
    '  return { orders, index, order }',
    '}',
    '',
    "app.post('/api/orders/:id/cancel', async (request, response) => {",
    '  try {',
    '    const found = await findCustomerOrder(request, response); if (!found) return',
    "    if (!['Processing', 'Accepted'].includes(found.order.status)) return response.status(400).json({ message: 'This order can no longer be cancelled.' })",
    '    const cancellation = { requested: true, requestedAt: new Date().toISOString(), reason: clean(request.body?.reason) || "Customer requested cancellation", refundStatus: found.order.paymentMethod === "Cash on Delivery" ? "Not applicable" : "Pending" }',
    '    if (found.reference) {',
    '      await found.reference.update({ status: "Cancelled", location: "Cancellation requested", cancellation })',
    '      return response.json({ order: { ...found.order, status: "Cancelled", location: "Cancellation requested", cancellation } })',
    '    }',
    '    found.order.status = "Cancelled"; found.order.location = "Cancellation requested"; found.order.cancellation = cancellation; await writeOrders(found.orders)',
    '    return response.json({ order: found.order })',
    '  } catch (error) { console.error("Order cancellation failed:", error); return response.status(500).json({ message: "Order could not be cancelled." }) }',
    '})',
    '',
    "app.post('/api/orders/:id/return', async (request, response) => {",
    '  try {',
    '    const found = await findCustomerOrder(request, response); if (!found) return',
    "    if (found.order.status !== 'Delivered') return response.status(400).json({ message: 'Return is available after delivery.' })",
    "    if (found.order.returnRequest?.status === 'Pending') return response.json({ order: found.order })",
    '    const returnRequest = { status: "Pending", requestedAt: new Date().toISOString(), reason: clean(request.body?.reason) || "Customer requested return", refundStatus: "Pending review" }',
    '    if (found.reference) { await found.reference.update({ returnRequest }); return response.json({ order: { ...found.order, returnRequest } }) }',
    '    found.order.returnRequest = returnRequest; await writeOrders(found.orders); return response.json({ order: found.order })',
    '  } catch (error) { console.error("Return request failed:", error); return response.status(500).json({ message: "Return request could not be created." }) }',
    '})',
    '',
    "app.post('/api/orders/:id/refund', async (request, response) => {",
    '  try {',
    '    const found = await findCustomerOrder(request, response); if (!found) return',
    "    if (![\"Cancelled\", \"Delivered\"].includes(found.order.status) && found.order.returnRequest?.status !== \"Approved\") return response.status(400).json({ message: 'Refund is not available for this order yet.' })",
    '    const refundRequest = { status: "Pending", requestedAt: new Date().toISOString(), method: found.order.paymentMethod || "Original payment method", amount: Number(found.order.total) || 0 }',
    '    if (found.reference) { await found.reference.update({ refundRequest }); return response.json({ order: { ...found.order, refundRequest } }) }',
    '    found.order.refundRequest = refundRequest; await writeOrders(found.orders); return response.json({ order: found.order })',
    '  } catch (error) { console.error("Refund request failed:", error); return response.status(500).json({ message: "Refund request could not be created." }) }',
    '})',
    ''
  ].join('\n')

  return { ...result, source: `${result.source}${injected}`, shortCircuit: true }
}
